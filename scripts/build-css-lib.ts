// Joins the component stylesheets into one file (DECISIONS #48). Kept separate from the
// script so the joining rules can be unit tested.

export interface CssSource {
  name: string;
  css: string;
}

// One layer order for the whole site, declared at the top of base.css and components.css:
// later layers win regardless of selector specificity, unlayered rules beat both.
export const LAYER_ORDER = "@layer base, components;";

export function joinComponents(sources: readonly CssSource[]): string {
  // Deterministic: byte-order sort by file name, independent of the file system's order.
  const sorted = [...sources].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  for (const { name, css } of sorted) {
    if (/@import\b/.test(css)) throw new Error(`${name}: @import isn't allowed in component files`);
    if (/@layer\b/.test(css)) throw new Error(`${name}: component files are wrapped in @layer components; don't declare layers`);
  }
  const body = sorted.map(({ name, css }) => `/* ---- ${name} ---- */\n${css.trim()}\n`).join("\n");
  return [
    "/* Generated by scripts/build-css.ts from public/styles/components/*.css. Don't edit. */",
    LAYER_ORDER,
    "",
    "@layer components {",
    "",
    body,
    "}",
    "",
  ].join("\n");
}
